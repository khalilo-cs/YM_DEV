"""Generate docs/DATABASE_SCHEMA.md and docs/API_REFERENCE.md from the code itself.

Deterministic output (no timestamps). tests/regression/test_docs_in_sync.py fails when the committed
files differ from what this script produces, so reference docs cannot silently drift from the code.

Usage: python scripts/gen_reference_docs.py [--check]
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DB_DOC = ROOT / "docs" / "DATABASE_SCHEMA.md"
API_DOC = ROOT / "docs" / "API_REFERENCE.md"

DB_NOTES = {
    "audit_events": "Append-only; HMAC hash chain (ADR-0004). Never updated or deleted by the platform.",
    "evidence_records": "Append-only; each row content-hashed and anchored in the audit chain.",
    "approval_requests": "Bound to (action, target, operation_digest); single-use; expires; revoked on cancel.",
    "api_tokens": "Only SHA-256 hashes of tokens are stored; every token expires.",
    "memory_records": "Versioned; verified rows are superseded, never overwritten silently.",
    "agent_runs": "One row per agent invocation (including denied ones) with input/output digests.",
    "project_members": "Per-project roles; a token role is the ceiling (ADR-0007).",
    "skills": "Primary key (id, version); a changed spec is a new version starting at PROPOSED.",
    "tasks": "Persistent ORION task state; lease columns prevent two workers running one task.",
    "task_steps": "One row per (task, step); completed steps are never re-run on resume.",
}


def database_schema() -> str:
    from yemendev.storage.db import Database
    from yemendev.storage.migrations import MIGRATIONS

    with tempfile.TemporaryDirectory() as tmp:
        db = Database(Path(tmp) / "schema.sqlite3")
        db.migrate()
        with db.read() as conn:
            tables = [r[0] for r in conn.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
            info = {t: conn.execute(f"PRAGMA table_info({t})").fetchall() for t in tables}  # noqa: S608
            fks = {t: conn.execute(f"PRAGMA foreign_key_list({t})").fetchall() for t in tables}  # noqa: S608
            idx = {t: [r[1] for r in conn.execute(f"PRAGMA index_list({t})") if not r[1].startswith("sqlite_")]
                   for t in tables}  # noqa: S608
    out = ["# Database Schema", "",
           "> Generated by `scripts/gen_reference_docs.py` from the migrations. Do not edit by hand.", "",
           f"Engine: SQLite (WAL, `synchronous=FULL`, foreign keys on). Schema version: "
           f"**{MIGRATIONS[-1][0]}** ({len(MIGRATIONS)} migrations). Tables: **{len(tables)}**.", "",
           "## Migrations", "", "| Version | Name |", "|---|---|"]
    out += [f"| {v} | `{n}` |" for v, n, _ in MIGRATIONS]
    rels = []
    for t in tables:
        for fk in fks[t]:
            rels.append(f"    {fk[2].upper()} ||--o{{ {t.upper()} : \"{fk[3]} -> {fk[4]}\"")
    out += ["", "## Relationships", "", "```mermaid", "erDiagram"] + sorted(set(rels)) + ["```", ""]
    for t in tables:
        out += [f"## `{t}`", ""]
        if t in DB_NOTES:
            out += [DB_NOTES[t], ""]
        out += ["| Column | Type | Not null | PK | References |", "|---|---|---|---|---|"]
        refs = {fk[3]: f"`{fk[2]}.{fk[4]}`" for fk in fks[t]}
        for col in info[t]:
            out.append(f"| `{col[1]}` | {col[2] or '-'} | {'yes' if col[3] else ''} | {col[5] or ''} | "
                       f"{refs.get(col[1], '')} |")
        if idx[t]:
            out += ["", "Indexes: " + ", ".join(f"`{i}`" for i in sorted(idx[t]))]
        out.append("")
    out += ["## Retention", "",
            "No automatic deletion is implemented. Audit, evidence and agent-run rows are append-only by design;",
            "deleting a project cascades to its scans, memory, tasks and memberships (foreign keys).",
            "A retention policy for long-running installations is **not implemented** (see FEATURE_STATUS).", ""]
    return "\n".join(out)


def _schema_name(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "-"
    if "$ref" in schema:
        return "`" + schema["$ref"].rsplit("/", 1)[-1] + "`"
    if schema.get("type") == "array":
        return "array of " + _schema_name(schema.get("items"))
    return schema.get("type", "object")


def api_reference() -> str:
    from yemendev.api.app import create_app
    from yemendev.core.config import Settings
    from yemendev.platform import Platform

    with tempfile.TemporaryDirectory() as tmp:
        spec = create_app(Platform(Settings(data_dir=Path(tmp) / "d"))).openapi()
    out = ["# API Reference (`/api/v1`)", "",
           "> Generated by `scripts/gen_reference_docs.py` from the FastAPI application. Do not edit by hand.",
           "> Interactive docs: `GET /api/docs` on a running server.", "",
           "**Authentication:** `Authorization: Bearer ydv_...` on every route except `GET /api/v1/health`.",
           "Authorization is per action and, for project resources, per project membership (ADR-0007).", "",
           "**Errors:** `{\"error\": {\"code\": ..., \"message\": ...}}` with codes `unauthenticated` (401),",
           "`permission_denied` (403), `not_found` (404), `conflict` (409), `precondition_failed` (412),",
           "`invalid_input` (413/422), `rate_limited` (429, with `Retry-After`), `unavailable` (503),",
           "`internal` (500, no internals exposed).", "",
           f"Routes: **{sum(len(v) for v in spec['paths'].values())}**.", "",
           "| Method | Path | Operation | Request body | Query parameters |", "|---|---|---|---|---|"]
    for path in sorted(spec["paths"]):
        for method, op in sorted(spec["paths"][path].items()):
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            qs = ", ".join(f"`{p['name']}`" for p in op.get("parameters", []) if p.get("in") == "query") or "-"
            out.append(f"| {method.upper()} | `{path}` | {op.get('summary', op.get('operationId', ''))} | "
                       f"{_schema_name(body)} | {qs} |")
    out += ["", "## Request schemas", ""]
    comps = spec.get("components", {}).get("schemas", {})
    used = sorted({_schema_name(op.get("requestBody", {}).get("content", {}).get("application/json", {})
                                .get("schema")).strip("`")
                   for v in spec["paths"].values() for op in v.values() if "requestBody" in op})
    for name in used:
        sch = comps.get(name, {})
        out += [f"### `{name}`", "", "| Field | Type | Required |", "|---|---|---|"]
        req = set(sch.get("required", []))
        for field, fs in sorted(sch.get("properties", {}).items()):
            t = fs.get("type") or _schema_name(fs) if ("$ref" in fs or "type" in fs) else "any"
            if "anyOf" in fs:
                t = " or ".join(_schema_name(x) if "$ref" in x else x.get("type", "any") for x in fs["anyOf"])
            out.append(f"| `{field}` | {t} | {'yes' if field in req else ''} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    sys.path.insert(0, str(ROOT / "src"))
    docs = {DB_DOC: database_schema(), API_DOC: api_reference()}
    if "--check" in sys.argv:
        stale = [p.name for p, text in docs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("out of date: " + ", ".join(stale) + " (run: python scripts/gen_reference_docs.py)")
            return 1
        print("reference docs are up to date")
        return 0
    for p, text in docs.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
